"""Claude Code against a local Ornith server, through a small wrapper script per profile.

The user's own Claude Code settings are never edited: the wrapper points only
its own process at the local server, so plain ``claude`` keeps using the
user's Anthropic account. Anthropic does not support routing Claude Code to
non-Claude models; the setup screen and DISCLAIMER.md say so.
"""

from __future__ import annotations

import os
import shlex
from collections.abc import Mapping
from pathlib import Path

from ornith_launcher import __version__
from ornith_launcher.config import atomic_write_text
from ornith_launcher.profiles import Profile
from ornith_launcher.ui.plain import context_label

ANTHROPIC_NOTICE = (
    "Anthropic's docs: \"Anthropic doesn't endorse, maintain, or audit third-party gateway "
    "products, and doesn't support routing Claude Code to non-Claude models through any gateway.\""
)
DEFAULT_TIMEOUT_MS = 600_000  # Claude Code's own default: 10 minutes
# Seconds to prefill a full prompt of each context on a DGX Spark with the 1.5 35B-A3B
# (design 14.3: 3.5 min to 240k, 9.8 min to 456k, 35.5 min to 917k). ESTIMATED elsewhere.
_PREFILL_SECONDS = ((262_144, 240), (524_288, 650), (1_048_576, 2400))


def api_timeout_ms(context: int) -> int:
    """At least 1.5 x the time to read a full prompt, and never below Claude Code's default."""
    seconds = next(
        (s for limit, s in _PREFILL_SECONDS if context <= limit), _PREFILL_SECONDS[-1][1]
    )
    return max(DEFAULT_TIMEOUT_MS, int(seconds * 1.5 * 1000))


def wrapper_dir(home: Path) -> Path:
    return home / ".local" / "bin"


def wrapper_path(home: Path, profile_name: str) -> Path:
    return wrapper_dir(home) / f"ornith-claude-{profile_name}"


def alias_path(home: Path) -> Path:
    return wrapper_dir(home) / "ornith-claude"


def display_name(profile: Profile) -> str:
    """The name Claude Code and OpenCode list: the model's own name, quant, tag and context.

    "Ornith-1.5-9B-uncensored Q8_0 [UNCENSORED], 262k context (local)". The repo's model name
    tells a community build from the official one; uncensored models always say so.
    """
    model = profile.model
    if model.repo and "/" in model.repo:
        name = model.repo.split("/", 1)[1]
        if name.lower().endswith("-gguf"):
            name = name[: -len("-gguf")]
    else:
        name = f"Ornith {model.version or '?'} {model.size_class or '?'}"
    if model.quant:
        name += f" {model.quant}"
    if model.uncensored:
        name += " [UNCENSORED]"
    return f"{name}, {context_label(profile.runtime.context)} context (local)"


def wrapper_script(profile: Profile) -> str:
    """The POSIX sh wrapper; Python (already required by the launcher) reads the server's JSON."""
    timeout = api_timeout_ms(profile.runtime.context)
    return f"""#!/bin/sh
# Generated by ornith-launcher {__version__} (unofficial), profile {profile.name}; safe to delete.
# Runs Claude Code against the local Ornith server, for this process only: plain `claude`
# keeps using your Anthropic account. Anthropic does not support Claude Code with
# non-Claude models.
URL='{profile.url}'
MODEL='{profile.runtime.alias}'
NAME={shlex.quote(display_name(profile))}
START='ornith-launcher launch {profile.name}'
PYTHON=$(command -v python3 || command -v python) || {{
    echo "Python 3 is needed to read the server's settings." >&2
    exit 1
}}
CTX=$("$PYTHON" - "$URL" "$MODEL" <<'PY'
import json, sys, urllib.request
try:
    with urllib.request.urlopen(sys.argv[1] + "/v1/models", timeout=5) as reply:
        data = json.load(reply)
except Exception:
    sys.exit(1)
for model in data.get("data", []):
    if model.get("id") == sys.argv[2]:
        print((model.get("meta") or {{}}).get("n_ctx") or "")
PY
) || {{
    echo "The Ornith server is not running. Start it with: $START" >&2
    exit 1
}}
if [ -z "$CTX" ]; then
    echo "$URL is running another model. Start this one with: $START" >&2
    exit 1
fi
export ANTHROPIC_BASE_URL="$URL"
export ANTHROPIC_AUTH_TOKEN=local
export ANTHROPIC_MODEL=opus
for slot in OPUS SONNET HAIKU FABLE; do
    export "ANTHROPIC_DEFAULT_${{slot}}_MODEL=$MODEL"
    export "ANTHROPIC_DEFAULT_${{slot}}_MODEL_NAME=$NAME"
done
export CLAUDE_CODE_MAX_CONTEXT_TOKENS="$CTX"
export CLAUDE_CODE_MAX_OUTPUT_TOKENS="${{CLAUDE_CODE_MAX_OUTPUT_TOKENS:-32000}}"
export CLAUDE_CODE_DISABLE_NONESSENTIAL_TRAFFIC=1
# A full prompt at this context can take longer to read than Claude Code's default timeout.
export API_TIMEOUT_MS="${{API_TIMEOUT_MS:-{timeout}}}"
exec claude "$@"
"""


def write_wrapper(home: Path, profile: Profile) -> Path:
    path = wrapper_path(home, profile.name)
    atomic_write_text(path, wrapper_script(profile), mode=0o755)
    return path


def point_alias(home: Path, wrapper: Path) -> Path | None:
    """Make ``ornith-claude`` run this profile's wrapper (the default profile's)."""
    link = alias_path(home)
    if link.exists() and not link.is_symlink():
        return None  # not ours: leave it alone
    if link.is_symlink():
        link.unlink()
    link.symlink_to(wrapper.name)
    return link


def on_path(directory: Path, env: Mapping[str, str]) -> bool:
    entries = [Path(p) for p in env.get("PATH", "").split(os.pathsep) if p]
    return any(entry.resolve() == directory.resolve() for entry in entries if entry.exists())
